import pandas as pd
import numpy as np

# ============================================================
# GreenMind AI Dataset V2
# 15 พืช x 300 ตัวอย่าง = 4,500 samples
#
# Features:
# N, P, K, temperature, humidity
#
# Label:
# crop
#
# หมายเหตุ:
# ข้อมูลที่สร้างขึ้นเป็น Synthetic Data สำหรับทดลอง Train AI
# ============================================================

crops_base = {
    'ผักบุ้งจีน': [50, 30, 40, 31.0, 78.0],
    'กวางตุ้ง': [60, 40, 50, 28.5, 72.0],
    'คะน้า': [80, 45, 60, 27.0, 78.0],

    'ผักชี': [40, 35, 35, 24.0, 65.0],
    'กะเพรา': [35, 25, 30, 31.5, 58.0],
    'พริกขี้หนู': [20, 15, 20, 29.0, 52.0],

    'มะเขือเทศ': [75, 50, 65, 25.0, 68.0],
    'แตงกวา': [55, 40, 50, 29.0, 72.0],
    'ถั่วฝักยาว': [25, 35, 30, 28.5, 58.0],

    'ข้าวโพดหวาน': [90, 55, 60, 28.0, 72.0],
    'กะหล่ำปลี': [85, 50, 70, 21.5, 72.0],
    'กรีนโอ๊ค': [50, 35, 45, 23.0, 65.0],

    'ฟักทอง': [50, 35, 60, 28.0, 65.0],
    'หัวไชเท้า': [55, 35, 50, 20.0, 65.0],
    'กระเทียม': [45, 30, 50, 22.0, 60.0]
}

# ------------------------------------------------------------
# ตั้งค่าจำนวนตัวอย่าง
# ------------------------------------------------------------
SAMPLES_PER_CROP = 300

# ใช้ seed เดิม เพื่อให้สร้างข้อมูลซ้ำได้เหมือนเดิม
np.random.seed(42)

rows = []

# ------------------------------------------------------------
# สร้างข้อมูลแต่ละพืช
# ------------------------------------------------------------
for crop_name, values in crops_base.items():

    n_base, p_base, k_base, temp_base, hum_base = values

    for _ in range(SAMPLES_PER_CROP):

        # N
        n = int(np.clip(
            np.random.normal(n_base, 4.0),
            0,
            150
        ))

        # P
        p = int(np.clip(
            np.random.normal(p_base, 3.0),
            0,
            100
        ))

        # K
        k = int(np.clip(
            np.random.normal(k_base, 4.0),
            0,
            150
        ))

        # Temperature
        temperature = round(
            np.clip(
                np.random.normal(temp_base, 1.2),
                15.0,
                40.0
            ),
            1
        )

        # Humidity
        humidity = round(
            np.clip(
                np.random.normal(hum_base, 3.5),
                20.0,
                100.0
            ),
            1
        )

        rows.append([
            n,
            p,
            k,
            temperature,
            humidity,
            crop_name
        ])

# ------------------------------------------------------------
# สร้าง DataFrame
# ------------------------------------------------------------
df = pd.DataFrame(
    rows,
    columns=[
        'N',
        'P',
        'K',
        'temperature',
        'humidity',
        'crop'
    ]
)

# ------------------------------------------------------------
# สุ่มลำดับข้อมูล
# ------------------------------------------------------------
df = df.sample(
    frac=1,
    random_state=42
).reset_index(drop=True)

# ------------------------------------------------------------
# บันทึก CSV
# ------------------------------------------------------------
filename = 'greenmind_dataset_v2.csv'

df.to_csv(
    filename,
    index=False,
    encoding='utf-8-sig'
)

# ------------------------------------------------------------
# ตรวจสอบข้อมูล
# ------------------------------------------------------------
print("=" * 60)
print("✅ สร้าง Dataset สำเร็จ")
print("=" * 60)

print("จำนวนชนิดพืช :", len(crops_base))
print("ตัวอย่างต่อพืช :", SAMPLES_PER_CROP)
print("จำนวนข้อมูลทั้งหมด :", len(df))
print("ชื่อไฟล์ :", filename)

print("\nจำนวนข้อมูลของแต่ละพืช:")
print(df['crop'].value_counts().sort_index())

print("\nตัวอย่างข้อมูล 10 แถวแรก:")
print(df.head(10))

print("\nคอลัมน์:")
print(df.columns.tolist())